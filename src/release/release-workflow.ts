import { ACTIONS, kind, type Kind } from "./registries.ts"
import type { Registry } from "./types.ts"

/*
 * The `release.yml` a public repo publishes itself with, rendered from its package's `registries`. Sync writes
 * it into the public tree and pushes `v<version>` beside it; the workflow then publishes that tag to every
 * registry through OIDC (no token secret), fails on any rejection, and waits until each registry serves it.
 */

/** Where the rendered workflow sits in a public repo. */
export const RELEASE_WORKFLOW = ".github/workflows/release.yml"

/* Every registry is retried 10 s apart, 60 times unless its kind says more; LIVE_CHECK_TRIES lets a local run of
 * the step give up sooner. */
const DEFAULT_LIVE_TRIES = 60
const liveStep = (registry: Registry, k: Kind) => `      - name: ${registry.kind} serves the version
${k.liveEnv ?? ""}        run: |
          NAME="$(${k.name})"
          for _ in $(seq "\${LIVE_CHECK_TRIES:-${k.tries ?? DEFAULT_LIVE_TRIES}}"); do
            if ${k.live}; then echo "${registry.kind} serves $NAME $VERSION"; exit 0; fi
            sleep 10
          done
          echo "::error::${registry.kind} does not serve $NAME $VERSION; the publish above did not land"
          exit 1
`

/** The release workflow for a package published to `registries` (at least one). */
export function releaseWorkflow(registries: readonly Registry[]): string {
	if (registries.length === 0) throw new Error("a release workflow needs at least one registry")
	const kinds = registries.map((registry) => ({ k: kind(registry), registry }))
	const checks = [...new Map(kinds.map(({ k }) => [k.version, k.file])).entries()]
		.map(
			([version, file]) => `          FOUND="$(${version})"
          [ "$FOUND" = "$VERSION" ] || { echo "::error::tag $TAG, but ${file} holds version $FOUND"; exit 1; }
`,
		)
		.join("")
	const permissions = [
		`      contents: ${registries.some((r) => r.kind === "github") ? "write" : "read"}`,
		...(kinds.some(({ k }) => k.oidc) ? ["      id-token: write"] : []),
	].join("\n")

	return `# Generated by honey-clients release sync from release.config.ts; the next sync overwrites any edit.
# Publishes the tag sync pushes (or the one given to a manual run) to: ${registries.map((r) => r.kind).join(", ")}.
name: release
on:
  push:
    tags: ["v*"]
  workflow_dispatch:
    inputs:
      tag:
        description: Tag to publish again, as vX.Y.Z
        required: true
        type: string
permissions:
  contents: read
concurrency:
  group: release
  cancel-in-progress: false
jobs:
  publish:
    runs-on: ubuntu-24.04
    permissions:
${permissions}
    defaults:
      run:
        shell: bash
    env:
      TAG: \${{ inputs.tag || github.ref_name }}
    steps:
      - uses: ${ACTIONS.checkout}
        with:
          ref: \${{ inputs.tag || github.ref }}
      - name: the tag is the version the package publishes
        run: |
          VERSION="\${TAG#v}"
${checks}          echo "VERSION=$VERSION" >> "$GITHUB_ENV"
${kinds.map(({ k, registry }) => k.publish + liveStep(registry, k)).join("")}`
}
